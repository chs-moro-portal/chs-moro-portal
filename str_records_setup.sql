-- CHS Moro Portal: STR Status Tracking Record
-- Run this complete script once in Supabase SQL Editor.
create table if not exists public.str_records (
  id bigint generated by default as identity primary key,
  name text not null,
  payroll text,
  old_school_semis text,
  new_school_semis text,
  pid text,
  created_at timestamptz not null default now()
);
alter table public.str_records enable row level security;
drop policy if exists "Public can view STR records" on public.str_records;
create policy "Public can view STR records" on public.str_records for select to anon, authenticated using (true);
drop policy if exists "Only Supabase admins can insert STR records" on public.str_records;
create policy "Only Supabase admins can insert STR records" on public.str_records for insert to authenticated with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
drop policy if exists "Only Supabase admins can update STR records" on public.str_records;
create policy "Only Supabase admins can update STR records" on public.str_records for update to authenticated using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin') with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
drop policy if exists "Only Supabase admins can delete STR records" on public.str_records;
create policy "Only Supabase admins can delete STR records" on public.str_records for delete to authenticated using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
grant select on public.str_records to anon, authenticated;
grant insert, update, delete on public.str_records to authenticated;
grant usage, select on sequence public.str_records_id_seq to authenticated;